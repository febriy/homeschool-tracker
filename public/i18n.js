export function staticTranslations(root) {
  const texts=[],attributes=[],walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()) {const node=walker.currentNode;if(node.parentElement.closest('script,style'))continue;const value=node.textContent.trim();if(value)texts.push([node,value]);}
  for(const element of root.querySelectorAll('[placeholder],[aria-label],[title]'))for(const name of ['placeholder','aria-label','title'])if(element.hasAttribute(name))attributes.push([element,name,element.getAttribute(name)]);
  return t=>{for(const [node,value]of texts)if(node.isConnected)node.textContent=t(value);for(const [element,name,value]of attributes)if(element.isConnected)element.setAttribute(name,t(value));};
}

